        => version == TRVersion.TR1 ? GetName((TR1Items)type) : GetName((TR2Items)type);

    public static string GetName(TR1Items type)
        => _tr1Names[(int)type];

    public static string GetName(TR2Items type)
        => _tr2Names[(int)type];

    public static int GetType(string name, TRVersion version)
        => version == TRVersion.TR1 ? (int)GetTR1Type(name) : (int)GetTR2Type(name);

    public static TR1Items GetTR1Type(string name)
        => _tr1ReverseMap.TryGetValue(name, out var type) ? (TR1Items)type : TR1Items.Unknown;

    public static TR2Items GetTR2Type(string name)
        => _tr2ReverseMap.TryGetValue(name, out var type) ? (TR2Items)type : TR2Items.Unknown;

